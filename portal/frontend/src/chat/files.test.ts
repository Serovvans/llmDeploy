import { describe, expect, it } from 'vitest';

import { CONFIG } from '../test/mockApi';
import { transcriptionErrorText } from './files';

describe('запись во вложении: причина ошибки расшифровки', () => {
  it.each([
    ['media_too_long', 'Запись „шум.mp3“ длиннее 20 минут — для вложения это слишком много. Добавьте её в базу знаний и задайте вопрос, отметив базу под полем ввода'],
    ['media_invalid', 'Файл „шум.mp3“ не подходит. Подойдут MP3, WAV, M4A, OGG, FLAC, MP4, MKV, WebM и MOV. Если формат верный — сохраните запись заново в MP3'],
    ['media_no_audio', 'В файле „шум.mp3“ нет звуковой дорожки — расшифровывать нечего'],
    ['no_text', 'В записи „шум.mp3“ не нашлось русской речи'],
    ['transcription_failed', 'Не удалось расшифровать запись „шум.mp3“. Уберите её и прикрепите заново'],
    ['internal_error', 'Не удалось расшифровать запись „шум.mp3“. Уберите её и прикрепите заново'],
    // Неизвестный код и отсутствие кода — тот же общий текст.
    ['код_из_будущей_версии', 'Не удалось расшифровать запись „шум.mp3“. Уберите её и прикрепите заново'],
    [null, 'Не удалось расшифровать запись „шум.mp3“. Уберите её и прикрепите заново'],
  ])('%s', (code, text) => {
    expect(transcriptionErrorText(code, 'шум.mp3', CONFIG.media)).toBe(text);
  });

  it('без конфигурации предел длительности неизвестен — общий текст, а не «undefined минут»', () => {
    expect(transcriptionErrorText('media_too_long', 'шум.mp3', null)).toBe(
      'Не удалось расшифровать запись „шум.mp3“. Уберите её и прикрепите заново',
    );
  });
});
