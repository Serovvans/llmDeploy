import { describe, expect, it } from 'vitest';

import { footnoteNumbers, markFootnotes, unmarkFootnotes } from './footnotes';

const SOURCES = new Set([1, 2, 3]);

/** Как на сервере: номера источников 1–3, на которые в тексте есть сноска. */
function cited(text: string): number[] {
  return [...footnoteNumbers(text)].filter((n) => SOURCES.has(n)).sort((a, b) => a - b);
}

describe('что считается сноской — те же случаи, что в тестах сервера', () => {
  it.each([
    ['Срок — 49 лет [1], см. также [2][3].', [1, 2, 3]],
    ['Ссылки [01], [0], [ 1 ], [1a], [10] и [7].', []],
    ['Массив coords[1] в тексте — тоже сноска по правилу.', [1]],
    ['```\narr[1]\n```\nпосле блока [2]', [2]],
    ['~~~sql\nSELECT a[1];\n~~~\n[3]', [3]],
    ['````\n```\nвнутри [1]\n```\nещё внутри [2]\n````\n[3]', [3]],
    ['```\nнезакрытый блок [1]\nдо конца текста [2]', []],
    ['   ```\nс отступом до трёх пробелов [1]\n   ```\n[2]', [2]],
    ['```\n[1]\n~~~\n[2]\n```\n[3]', [3]],
    ['Текст\n\n    код с отступом [1]\n\tтабуляция [2]\n\nтекст [3]', [3]],
    ['Встроенный `код [1]` и текст [2].', [2]],
    ['Двойные ``код ` с апострофом [1]`` и [2].', [2]],
    ['Одинокий ` апостроф не начинает код [1].', [1]],
    ['Код на две\nстроки `начало [1]\nконец` и [2].', [2]],
    ['', []],
  ])('%j → %j', (text, expected) => {
    expect(cited(text)).toEqual(expected);
  });

  it('строка с отступом — код, даже если Markdown счёл бы её продолжением абзаца', () => {
    expect(cited('Абзац,\n    который продолжается с отступом [1]\nи дальше [2]')).toEqual([2]);
  });
});

describe('разметка сносок для отрисовки', () => {
  const show = (text: string) => markFootnotes(text, SOURCES).replaceAll('', '«').replaceAll('', '»');

  it('метки стоят ровно на засчитанных сносках с известным источником', () => {
    expect(show('Срок [1], в коде `a[2]`, нет источника [9], ещё [3].')).toBe(
      'Срок «1», в коде `a[2]`, нет источника [9], ещё «3».',
    );
    expect(show('```\nx[1]\n```\nпосле [2]')).toBe('```\nx[1]\n```\nпосле «2»');
    expect(show('Абзац\n    с отступом [1]\nдальше [1]')).toBe('Абзац\n    с отступом [1]\nдальше «1»');
    expect(show('Одинокий ` апостроф [1]')).toBe('Одинокий ` апостроф «1»');
  });

  it('текст без сносок не меняется; метки возвращаются в вид [n]', () => {
    const plain = 'Просто текст с `кодом[1]` и [7].';
    expect(markFootnotes(plain, SOURCES)).toBe(plain);
    expect(unmarkFootnotes(markFootnotes('Срок [1] и [2].', SOURCES))).toBe('Срок [1] и [2].');
  });
});
