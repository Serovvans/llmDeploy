function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100;
  const mod10 = n % 10;
  if (mod100 >= 11 && mod100 <= 14) {
    return many;
  }
  if (mod10 === 1) {
    return one;
  }
  return mod10 >= 2 && mod10 <= 4 ? few : many;
}

const SMALL_NUMBERS: Record<number, [genitive: string, nominative: string]> = {
  2: ['двух', 'два'],
  3: ['трёх', 'три'],
  4: ['четырёх', 'четыре'],
};

/** «кроме последних двух вопросов с ответами» (концепция §4.9): 1 — единственное число, 2–4 словом, от 5 — цифрами. */
function exceptLast(keep: number): string {
  if (keep === 1) {
    return 'кроме последнего вопроса с ответом';
  }
  const count = SMALL_NUMBERS[keep]?.[0] ?? String(keep);
  return `кроме последних ${count} ${plural(keep, 'вопроса', 'вопросов', 'вопросов')} с ответами`;
}

/** «последние два вопроса с ответами не сжимаются» — то же правило в именительном падеже. */
function lastKept(keep: number): string {
  if (keep === 1) {
    return 'последний вопрос с ответом не сжимается';
  }
  const count = SMALL_NUMBERS[keep]?.[1] ?? String(keep);
  return `последние ${count} ${plural(keep, 'вопрос', 'вопроса', 'вопросов')} с ответами не сжимаются`;
}

/** «через 5 минут»: срок округляется вверх до минут, меньше минуты — «через минуту» (§5.1). */
export function retryAfter(seconds: number): string {
  const minutes = Math.ceil(seconds / 60);
  if (minutes <= 1) {
    return 'через минуту';
  }
  return `через ${minutes} ${plural(minutes, 'минуту', 'минуты', 'минут')}`;
}

/** «Петров А. С.» из полного ФИО — в таблице и просмотре документов (концепция §4.4, §5.6). */
export function shortName(fullName: string): string {
  const [surname = '', ...rest] = fullName.trim().split(/\s+/);
  return [surname, ...rest.map((part) => `${part.charAt(0)}.`)].join('\u00a0');
}

function pad2(value: number): string {
  return String(value).padStart(2, '0');
}

/** Момент записи (концепция §4.3): до часа — `мм:сс`, от часа — `ч:мм:сс`. */
export function formatTimecode(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const rest = `${pad2(Math.floor((seconds % 3600) / 60))}:${pad2(seconds % 60)}`;
  return hours > 0 ? `${hours}:${rest}` : rest;
}

/** Момент записи словами для экранного чтения, в родительном падеже — после «с»: «12 минут 40 секунд»; нулевые части опускаются. */
export function spokenTimecode(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const parts = [
    hours > 0 ? `${hours} ${plural(hours, 'часа', 'часов', 'часов')}` : '',
    minutes > 0 ? `${minutes} ${plural(minutes, 'минуты', 'минут', 'минут')}` : '',
    seconds % 60 > 0 || seconds === 0 ? `${seconds % 60} ${plural(seconds % 60, 'секунды', 'секунд', 'секунд')}` : '',
  ];
  return parts.filter(Boolean).join(' ');
}

/** Длительность записи (концепция §4.4): «1 ч 12 мин», короче часа — «12 мин», короче минуты — «40 с». */
export function formatDuration(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  if (hours > 0) {
    return `${hours} ч ${minutes} мин`;
  }
  return minutes > 0 ? `${minutes} мин` : `${seconds} с`;
}

/** Предел длины записи в родительном падеже — после «длиннее»: «3 часов», «90 минут». */
function durationLimit(minutes: number): string {
  if (minutes % 60 === 0) {
    return `${minutes / 60} ${plural(minutes / 60, 'часа', 'часов', 'часов')}`;
  }
  return `${minutes} ${plural(minutes, 'минуты', 'минут', 'минут')}`;
}

/** Срок временной блокировки входа (§5.10): сегодня — «до 14:35», иначе — «до 06.10.2026, 09:10». */
export function lockedUntil(iso: string, now: Date): string {
  const date = new Date(iso);
  const pad = (value: number) => String(value).padStart(2, '0');
  const time = `${pad(date.getHours())}:${pad(date.getMinutes())}`;
  return date.toDateString() === now.toDateString()
    ? `до ${time}`
    : `до ${pad(date.getDate())}.${pad(date.getMonth() + 1)}.${date.getFullYear()}, ${time}`;
}

/** Дата по правилу §8.1: сегодня и вчера — словами со временем, иначе `12.09.2026`. */
export function formatDate(iso: string, now: Date = new Date()): string {
  const date = new Date(iso);
  const startOfDay = (value: Date) => new Date(value.getFullYear(), value.getMonth(), value.getDate()).getTime();
  const days = Math.round((startOfDay(now) - startOfDay(date)) / (24 * 60 * 60 * 1000));
  const pad = (value: number) => String(value).padStart(2, '0');
  const time = `${pad(date.getHours())}:${pad(date.getMinutes())}`;
  if (days === 0) {
    return `сегодня, ${time}`;
  }
  if (days === 1) {
    return `вчера, ${time}`;
  }
  return `${pad(date.getDate())}.${pad(date.getMonth() + 1)}.${date.getFullYear()}`;
}

/**
 * «‹размер›» в текстах раздела «Код» (концепция §8.3): меньше 1 МБ — в КБ, от 1 МБ — в МБ;
 * не целое — с одним знаком после запятой. 1 КБ = 1024 байта.
 */
export function formatSize(bytes: number): string {
  const mb = 1024 * 1024;
  const [value, unit] = bytes < mb ? [bytes / 1024, 'КБ'] : [bytes / mb, 'МБ'];
  const rounded = Math.round(value * 10) / 10;
  return `${rounded.toLocaleString('ru-RU', { maximumFractionDigits: 1 })} ${unit}`;
}

