/**
 * Текст для отказа, у которого на экране нет своей формулировки: нет связи, сбой сервера,
 * иначе — готовый русский текст сервера (контракт §1.3) или общая ошибка действия.
 */
export function errorText(error: unknown): string {
  if (error instanceof NetworkError) {
    return texts.common.noConnection;
  }
  if (error instanceof ApiError) {
    if (error.code === 'internal_error' || error.code === 'service_unavailable') {
      return texts.common.serverFailure;
    }
    if (error.message) {
      return error.message;
    }
  }
  return texts.common.actionFailed;
}
